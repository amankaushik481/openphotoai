export const V1_BASE_PATH = "/api/v1";
export const SECURITY_SCHEME = "ApiKeyAuth";

/** Public base URL of the API (servers[0].url). */
export function apiBaseUrl(origin: string = APP.url): string {
  return `${origin.replace(/\/$/, "")}${V1_BASE_PATH}`;
}

/** Names of the plans that include API access (e.g. ["Pro", "Studio"]). */
export function apiPlanNames(): string[] {
  return Object.values(PLANS)
    .filter((p) => p.limits.apiAccess)
    .map((p) => p.name);
}

/** HTTP status of an API error code (single source: AppError in src/server/http.ts). */
export function errorStatusOf(code: ApiErrorCode): number {
  return new AppError(code, "").status;
}

/* ───────────────────────────── Zod → JSON Schema ───────────────────────────── */

function fromZod(schema: z.ZodType, docs: Record<string, string> = {}): JsonSchema {
  const json = z.toJSONSchema(schema, {
    io: "input",
    target: "draft-2020-12",
    unrepresentable: "any",
  }) as JsonSchema & {
    $schema?: string;
  };
  delete json.$schema;
  for (const [name, prop] of Object.entries(json.properties ?? {})) {
    const doc = docs[name];
    if (doc && !prop.description) prop.description = doc;
  }
  return json;
}

