function errorResponses(): Record<string, ResponseObject> {
  const out: Record<string, ResponseObject> = {};
  for (const [status, r] of Object.entries(ERROR_RESPONSES)) {
    out[r.name] = {
      description: r.description,
      ...(status === "429" ? { headers: { "Retry-After": { $ref: "#/components/headers/Retry-After" } } } : {}),
      content: {
        "application/json": { schema: ref("Error"), example: { error: { code: r.code, message: r.message } } },
      },
    };
  }
  return out;
}

/* ───────────────────────────── operations ───────────────────────────── */

function curlSample(op: V1Operation, baseUrl: string): string {
  const url = `${baseUrl}${op.path.replace(/\{(\w+)\}/g, (_, p: string) => `$${p.toUpperCase()}`)}`;
  const lines = [`curl${op.method === "get" ? "" : ` -X ${op.method.toUpperCase()}`} "${url}"`];
  if (op.scope) lines.push(`  -H "Authorization: Bearer $API_KEY"`);
  const example = op.body ? Object.values(op.body.examples)[0] : undefined;
  if (op.idempotencyKey) lines.push(`  -H "Idempotency-Key: $(uuidgen)"`);
  if (example) {
    lines.push(`  -H "Content-Type: application/json"`);
    lines.push(`  -d '${JSON.stringify(example.value)}'`);
  }
  for (const [name, field] of Object.entries(op.multipart?.schema.properties ?? {})) {
    const value = field.format === "binary" ? "@photo.jpg" : String(field.enum?.[0] ?? "");
    lines.push(`  -F "${name}=${value}"`);
  }
  return lines.join(" \\\n");
}

function buildOperation(op: V1Operation, baseUrl: string): OperationObject {
  const parameters: OperationObject["parameters"] = [];
  for (const [name, description] of Object.entries(op.pathParams ?? {})) {
    parameters.push({
      name,
      in: "path",
      required: true,
      description,
      schema: { type: "string", minLength: 1, maxLength: 64 },
    });
  }
  if (op.query) {
    const json = fromZod(op.query.schema, op.query.docs);
    const required = new Set(json.required ?? []);
    for (const [name, schema] of Object.entries(json.properties ?? {})) {
      const { description, ...rest } = schema;
      const param: ParameterObject = { name, in: "query", required: required.has(name), schema: rest };
      if (description) param.description = description;
      parameters.push(param);
    }
  }
  if (op.idempotencyKey) parameters.push({ $ref: "#/components/parameters/IdempotencyKey" });

  const okHeaders = op.scope
    ? Object.fromEntries(
        ["X-RateLimit-Limit", "X-RateLimit-Remaining", "X-RateLimit-Reset"].map((h) => [
          h,
          { $ref: `#/components/headers/${h}` },
        ]),
      )
    : undefined;
  const responses: OperationObject["responses"] = {
    "200": {
      description: op.response.description,
      ...(okHeaders ? { headers: okHeaders } : {}),
      content: {
        "application/json": {
          schema: op.response.schema,
          ...(op.response.example !== undefined ? { example: op.response.example } : {}),
        },
      },
    },
  };
  const statuses = new Set<ErrorStatus>([...(op.scope ? ([401, 403, 429] as const) : []), ...op.errors]);
  for (const status of [...statuses].sort((a, b) => a - b)) {
    responses[String(status)] = { $ref: `#/components/responses/${ERROR_RESPONSES[status].name}` };
  }

  const security = op.scope ? [{ [SECURITY_SCHEME]: [op.scope] }] : [];
  const scopeNote = op.scope ? `\n\nRequires an API key with the \`${op.scope}\` scope (or \`*\`).` : "";
  return {
    operationId: op.operationId,
    summary: op.summary,
    description: `${op.description}${scopeNote}`,
    tags: [op.tag],
    security,
    ...(parameters.length ? { parameters } : {}),
    ...(op.body
      ? {
          requestBody: {
            description: op.body.description,
            required: true,
            content: { "application/json": { schema: ref(op.body.schema), examples: op.body.examples } },
          },
        }
      : op.multipart
        ? {
            requestBody: {
              description: op.multipart.description,
              required: true,
              content: { "multipart/form-data": { schema: op.multipart.schema } },
            },
          }
        : {}),
    responses,
    "x-required-scope": op.scope,
    "x-codeSamples": [{ lang: "Shell", label: "curl", source: curlSample(op, baseUrl) } satisfies CodeSample],
  };
}

/* ───────────────────────────── document ───────────────────────────── */

function description(): string {
  const plans = apiPlanNames().join(" and ");
  const perKey = RATE_LIMITS.apiPerMinute;
  return [
    `REST API for ${APP.name}: create photos, edits and videos of yourself programmatically.`,
    "",
    `**Authentication.** Create a key at ${APP.url}/app/api-keys (${plans} plans) and send it as \`Authorization: Bearer os_live_…\`. Keys have scopes: \`read\`, \`generate\` or \`*\` (all).`,
    "",
    `**Rate limits.** ${perKey.limit} requests per ${perKey.windowSec} s per key (\`X-RateLimit-*\` headers), plus per-account job limits. Over the limit you get \`429\` with \`Retry-After\`.`,
    "",
    "**Jobs** are asynchronous: create one, then poll `GET /jobs/{id}` every 2-5 s until its status is `succeeded`, `failed`, `canceled` or `blocked`. Credits are refunded automatically for failures and blocked outputs.",
    "",
    '**Errors** always look like `{ "error": { "code", "message", "details?" } }`.',
  ].join("\n");
}

export interface BuildSpecOptions {
  /** Public origin (defaults to NEXT_PUBLIC_APP_URL). */
  origin?: string;
}

export function buildOpenApiSpec(opts: BuildSpecOptions = {}): OpenApiDocument {
  const baseUrl = apiBaseUrl(opts.origin);
  const paths: OpenApiDocument["paths"] = {};
  for (const op of Object.values(v1Operations) as V1Operation[]) {
    (paths[op.path] ??= {})[op.method] = buildOperation(op, baseUrl);
  }

  return {
    openapi: "3.1.0",
    info: {
      title: `${APP.name} API`,
      version: "1.0.0",
      summary: APP.tagline,
      description: description(),
      contact: { name: `${APP.name} support`, email: APP.supportEmail, url: `${APP.url}/docs/api` },
      license: { name: "MIT", identifier: "MIT" },
    },
    jsonSchemaDialect: "https://spec.openapis.org/oas/3.1/dialect/base",
    servers: [{ url: baseUrl, description: APP.name }],
    tags: V1_TAGS,
    security: [{ [SECURITY_SCHEME]: [] }],
    paths,
    components: {
      schemas: { ...requestSchemas(), ...DTO_SCHEMAS },
      responses: errorResponses(),
      parameters: {
        IdempotencyKey: {
          name: "Idempotency-Key",
          in: "header",
          required: false,
          description:
            "Any unique string (1-200 printable ASCII characters, e.g. a UUID). Retrying with the same key returns the original job instead of creating (and charging for) a new one.",
          schema: { type: "string", minLength: 1, maxLength: 200, pattern: "^[\\x21-\\x7e]+$" },
          example: "6f1c2a7e-8a7b-4e0f-9d43-1b2c3d4e5f60",
        },
      },
      headers: RATE_HEADERS,
      securitySchemes: {
        [SECURITY_SCHEME]: {
          type: "http",
          scheme: "bearer",
          bearerFormat: "os_live_…",
          description: `API key from ${APP.url}/app/api-keys, sent as \`Authorization: Bearer os_live_…\`.`,
        },
      },
    },
  };
}

