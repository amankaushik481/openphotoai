/** "pose_copy" -> "PoseCopyJobInput". */
export function jobInputSchemaName(type: string): string {
  return `${type.replace(/(^|_)([a-z])/g, (_, __, c: string) => c.toUpperCase())}JobInput`;
}

function requestSchemas(): Record<string, JsonSchema> {
  const schemas: Record<string, JsonSchema> = {};
  const mapping: Record<string, string> = {};
  for (const option of createJobRequest.options) {
    const type = option.shape.type.value;
    const name = jobInputSchemaName(type);
    schemas[name] = { title: name, description: JOB_TYPE_DOCS[type], ...fromZod(option, JOB_FIELD_DOCS) };
    mapping[type] = `#/components/schemas/${name}`;
  }
  schemas.CreateJobRequest = {
    description: "Body of `POST /jobs`, discriminated by `type`.",
    oneOf: Object.values(mapping).map((r) => ({ $ref: r })),
    discriminator: { propertyName: "type", mapping },
  };
  schemas.CreateBatchRequest = {
    title: "CreateBatchRequest",
    description: "Body of `POST /batches`. The model must be `ready`.",
    ...fromZod(createBatchRequest, { ...JOB_FIELD_DOCS, quality: "`standard` or `high` (2× credits)." }),
  };
  return schemas;
}

