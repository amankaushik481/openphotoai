/**
 * Consent for a demo model. Demo mode is mock-only (env.ts refuses DEMO_MODE with a real AI or
 * payment provider) and the selfie is synthetic, so there is no person to run the live camera +
 * liveness challenge with. The selfie still goes through the real consent safety check (exactly one
 * adult face, not sexual, not a public figure) and its embedding becomes the identity every
 * training photo must match. The consent record says plainly how it was made: `captureMethod:
 * "demo-seed"`.
 */
import { createHash } from "node:crypto";
import { and, eq, sql } from "drizzle-orm";
import { db } from "@/db";
import { consentRecords, identityModels } from "@/db/schema";
import type { IdentityModelRow, UserRow } from "@/db/types";
import { newId } from "@/lib/ids";
import { errors } from "@/server/http";
import { normalizeImage } from "@/server/images/process";
import { verifyConsentSelfie } from "@/server/safety";
import { getStorage, storageKeys } from "@/server/storage";

export const DEMO_CAPTURE_METHOD = "demo-seed";
const SELFIE_MAX_SIDE = 1600;

export interface DemoConsentInput {
  user: UserRow;
  model: IdentityModelRow;
  selfie: Uint8Array;
  ipAddress: string | null;
  userAgent: string | null;
}

/** Verify the synthetic selfie and attach it (+ its embedding) to a fresh demo model. */
export async function seedDemoConsent(input: DemoConsentInput): Promise<IdentityModelRow> {
  const { user, model } = input;
  const normalized = await normalizeImage(input.selfie, { maxSide: SELFIE_MAX_SIDE });
  const verified = await verifyConsentSelfie(normalized.bytes, { userId: user.id, modelId: model.id });

  const recordId = newId("cns");
  const key = storageKeys.consentSelfie(user.id, model.id, recordId);
  const storage = getStorage();
  await storage.put(key, normalized.bytes, { contentType: normalized.mimeType });

  try {
    const updated = await db.transaction(async (tx) => {
      const [row] = await tx
        .update(identityModels)
        .set({
          consentSelfieKey: key,
          consentEmbedding: verified.embedding,
          consentVerifiedAt: sql`now()`,
          status: "collecting",
        })
        .where(
          and(
            eq(identityModels.id, model.id),
            eq(identityModels.userId, user.id),
            eq(identityModels.status, "awaiting_consent"),
          ),
        )
        .returning();
      if (!row) throw errors.conflict("The demo model changed while it was being set up.");
      await tx.insert(consentRecords).values({
        id: recordId,
        userId: user.id,
        modelId: model.id,
        kind: "training_selfie",
        ipAddress: input.ipAddress,
        userAgent: input.userAgent?.slice(0, 500) ?? null,
        evidence: {
          captureMethod: DEMO_CAPTURE_METHOD,
          demo: true,
          note: "Synthetic selfie generated by demo mode (mock providers only); no real person involved.",
          faceConfidence: verified.face.primary?.confidence ?? null,
          age: verified.age,
          faces: verified.face.count,
          selfieSha256: createHash("sha256").update(normalized.bytes).digest("hex"),
          storageKey: key,
          width: normalized.width,
          height: normalized.height,
        },
      });
      return row;
    });
    return updated;
  } catch (err) {
    await storage.delete(key).catch(() => undefined);
    throw err;
  }
}
