let cleanupStorage: () => Promise<void>;
beforeAll(async () => {
  cleanupStorage = await useTempStorage();
});
afterAll(async () => {
  await cleanupStorage();
});

let u: UserRow;
let model: IdentityModelRow;
let person: MediaRow;
let garment: UploadRow;

/** A stored image generated by OpenShoot for `userId` (a finished generate job + its media row). */
async function storedPhoto(userId: string, modelId: string | null, over: Partial<MediaRow> = {}): Promise<MediaRow> {
  const job = await createTestJob(userId, {
    modelId,
    status: "succeeded",
    input: jobInputSchema.parse({ type: "generate", modelId: modelId ?? "mdl_gone", prompt: "portrait of {subject}", numImages: 1 }),
  });
  const row = await createTestMedia(userId, { jobId: job.id, modelId, mimeType: "image/png", ...over });
  await getStorage().put(row.storageKey, await pngBytes(64, 80), { contentType: "image/png" });
  return row;
}

async function storedGarment(userId: string, purpose: UploadRow["purpose"] = "garment"): Promise<UploadRow> {
  const row = await createTestUpload(userId, { purpose, mimeType: "image/png" });
  await getStorage().put(row.storageKey, await pngBytes(48, 48), { contentType: "image/png" });
  return row;
}

const tryOn = (over: Partial<Extract<JobInput, { type: "try_on" }>> = {}): JobInput =>
  tryOnJobInput.parse({ type: "try_on", personMediaId: person.id, garmentUploadId: garment.id, ...over });

/** Capture what the handler sends to the provider (still delegating to the mock). */
function spyOnTryOn(): TryOnInput[] {
  const calls: TryOnInput[] = [];
  const provider = overrideMockAI();
  const original = provider.submitTryOn.bind(provider);
  provider.submitTryOn = async (input, opts) => {
    calls.push(input);
    return original(input, opts);
  };
  return calls;
}

beforeEach(async () => {
  await createTestDb();
  resetSafety();
  setProviderOverrides(null);
  u = await createTestUser({ credits: 20, plan: "pro", hasPaid: true });
  model = await createTestModel(u.id);
  person = await storedPhoto(u.id, model.id);
  garment = await storedGarment(u.id);
});
afterEach(() => {
  setProviderOverrides(null);
  vi.restoreAllMocks();
});

describe("try-on ownership guards", () => {
  it("rejects another user's photo as not_found without charging", async () => {
    const other = await createTestUser({ credits: 20 });
    const theirs = await storedPhoto(other.id, (await createTestModel(other.id)).id);
    await expect(createJob(u, tryOn({ personMediaId: theirs.id }))).rejects.toMatchObject({ code: "not_found" });
    expect(await db.select().from(jobs).where(eq(jobs.type, "try_on"))).toHaveLength(0);
    expect(await getBalance(u.id)).toBe(20);
  });

  it("rejects another user's garment upload as not_found", async () => {
    const other = await createTestUser();
    const theirs = await storedGarment(other.id);
    await expect(createJob(u, tryOn({ garmentUploadId: theirs.id }))).rejects.toMatchObject({ code: "not_found" });
    expect(await getBalance(u.id)).toBe(20);
  });

  it("rejects uploads that weren't uploaded as a garment", async () => {
    const reference = await storedGarment(u.id, "reference");
    await expect(createJob(u, tryOn({ garmentUploadId: reference.id }))).rejects.toMatchObject({ code: "validation_error" });
    const mask = await storedGarment(u.id, "mask");
    await expect(createJob(u, tryOn({ garmentUploadId: mask.id }))).rejects.toMatchObject({ code: "validation_error" });
    expect(await getBalance(u.id)).toBe(20);
  });

  it("rejects deleted or removed photos and videos", async () => {
    const deleted = await storedPhoto(u.id, model.id, { deletedAt: new Date() });
    await expect(createJob(u, tryOn({ personMediaId: deleted.id }))).rejects.toMatchObject({ code: "not_found" });
    const removed = await storedPhoto(u.id, model.id, { removedAt: new Date() });
    await expect(createJob(u, tryOn({ personMediaId: removed.id }))).rejects.toMatchObject({ code: "not_found" });
    const video = await storedPhoto(u.id, model.id, { kind: "video", mimeType: "video/mp4" });
    await expect(createJob(u, tryOn({ personMediaId: video.id }))).rejects.toMatchObject({ code: "validation_error" });
    expect(await getBalance(u.id)).toBe(20);
  });

  it("rejects a garment whose stored safety verdict is blocked", async () => {
    const blocked = await createTestUpload(u.id, {
      purpose: "garment",
      moderation: { checkedAt: new Date().toISOString(), provider: "mock", allowed: false, categories: ["sexual"] },
    });
    await expect(createJob(u, tryOn({ garmentUploadId: blocked.id }))).rejects.toMatchObject({ code: "content_blocked" });
  });

  it("rejects unknown categories at the schema level", () => {
    expect(() => tryOn({ category: "shoes" as never })).toThrow();
    expect(tryOn()).toMatchObject({ category: "auto" });
  });
});

describe("try-on lifecycle (mock provider)", () => {
  it("charges 3 credits, submits person + garment + category and stores the result under the person photo", async () => {
    safetyState.defaultLikeness = 0.92;
    const calls = spyOnTryOn();
    const job = await createJob(u, tryOn({ category: "tops" }));
    expect(job.status).toBe("running");
    expect(job.type).toBe("try_on");
    expect(job.creditsCharged).toBe(CREDIT_COSTS.tryOn);
    expect(job.sourceMediaId).toBe(person.id);
    expect(job.modelId).toBe(model.id);
    expect(await getBalance(u.id)).toBe(20 - CREDIT_COSTS.tryOn);

    expect(calls).toHaveLength(1);
    expect(calls[0]!.category).toBe("tops");
    expect(calls[0]!.personImageUrl).toMatch(/^mock:\/\//);
    expect(calls[0]!.garmentImageUrl).toMatch(/^mock:\/\//);
    expect(calls[0]!.personImageUrl).not.toBe(calls[0]!.garmentImageUrl);

    const plan = job.output?.plan as TryOnPlanData;
    expect(plan).toMatchObject({ personKey: person.storageKey, garmentKey: garment.storageKey, category: "tops", scoreLikeness: true });

    const done = await syncJob(job.id);
    expect(done.status).toBe("succeeded");
    expect(done.output?.mediaIds).toHaveLength(1);

    const [result] = await db.select().from(media).where(eq(media.jobId, job.id));
    expect(result!.userId).toBe(u.id);
    expect(result!.kind).toBe("image");
    expect(result!.parentMediaId).toBe(person.id);
    expect(result!.modelId).toBe(model.id);
    expect(result!.hidden).toBe(false);
    expect(result!.scores?.likeness).toBeCloseTo(0.92);
    expect(await getStorage().exists(result!.storageKey)).toBe(true);

    const dto = await toJobDTO(done);
    expect(dto.media).toHaveLength(1);
    expect(dto.media[0]!.parentMediaId).toBe(person.id);
    expect(dto.creditsRefunded).toBe(0);
    expect(await getBalance(u.id)).toBe(20 - CREDIT_COSTS.tryOn);
  });

  it("applies the likeness guarantee: a result that doesn't look like you is hidden and refunded", async () => {
    safetyState.defaultLikeness = 0.2;
    const job = await createJob(u, tryOn());
    const done = await syncJob(job.id);
    expect(done.status).toBe("succeeded");
    const [result] = await db.select().from(media).where(eq(media.jobId, job.id));
    expect(result!.hidden).toBe(true);
    expect(result!.scores?.likeness).toBeCloseTo(0.2);
    expect(done.creditsRefunded).toBe(CREDIT_COSTS.tryOn);
    expect(await getBalance(u.id)).toBe(20);
  });

  it("skips likeness scoring for together (multi-person) photos", async () => {
    safetyState.defaultLikeness = 0.1;
    const friend = await createTestModel(u.id, { name: "Friend" });
    const together = await createTestJob(u.id, {
      modelId: model.id,
      status: "succeeded",
      input: jobInputSchema.parse({ type: "multi_person", modelIds: [model.id, friend.id], prompt: "at the beach" }),
    });
    const scene = await createTestMedia(u.id, { jobId: together.id, modelId: model.id, mimeType: "image/png" });
    await getStorage().put(scene.storageKey, await pngBytes(), { contentType: "image/png" });

    const job = await createJob(u, tryOn({ personMediaId: scene.id }));
    expect((job.output?.plan as TryOnPlanData).scoreLikeness).toBe(false);
    const done = await syncJob(job.id);
    const [result] = await db.select().from(media).where(eq(media.jobId, done.id));
    expect(result!.scores?.likeness).toBeUndefined();
    expect(result!.hidden).toBe(false);
    expect(result!.parentMediaId).toBe(scene.id);
    expect(done.creditsRefunded).toBe(0);
  });

  it("doesn't score against a model that no longer belongs to the user", async () => {
    const orphan = await storedPhoto(u.id, null);
    const job = await createJob(u, tryOn({ personMediaId: orphan.id }));
    expect(job.modelId).toBeNull();
    expect((job.output?.plan as TryOnPlanData).scoreLikeness).toBe(false);
    const done = await syncJob(job.id);
    expect(done.status).toBe("succeeded");
  });

  it("refunds everything when the provider fails", async () => {
    const provider = overrideMockAI();
    provider.getStatus = async () => ({ state: "failed", error: "garment not detected" });
    const job = await createJob(u, tryOn());
    expect(await getBalance(u.id)).toBe(20 - CREDIT_COSTS.tryOn);
    const done = await syncJob(job.id);
    expect(done.status).toBe("failed");
    expect(done.creditsRefunded).toBe(CREDIT_COSTS.tryOn);
    expect(await getBalance(u.id)).toBe(20);
    expect(await db.select().from(media).where(eq(media.jobId, job.id))).toHaveLength(0);
  });

  it("refunds when the submit itself fails", async () => {
    const provider = overrideMockAI();
    provider.submitTryOn = async () => {
      throw new Error("provider down");
    };
    await expect(createJob(u, tryOn())).rejects.toMatchObject({ code: "provider_error" });
    const [row] = await db.select().from(jobs).where(eq(jobs.type, "try_on"));
    expect(row!.status).toBe("failed");
    expect(await getBalance(u.id)).toBe(20);
  });

  it("fails with insufficient credits before submitting", async () => {
    const poor = await createTestUser({ credits: 2, plan: "pro", hasPaid: true });
    const theirModel = await createTestModel(poor.id);
    const photo = await storedPhoto(poor.id, theirModel.id);
    const theirGarment = await storedGarment(poor.id);
    const calls = spyOnTryOn();
    await expect(
      createJob(poor, tryOn({ personMediaId: photo.id, garmentUploadId: theirGarment.id })),
    ).rejects.toMatchObject({ code: "insufficient_credits" });
    expect(calls).toHaveLength(0);
    expect(await getBalance(poor.id)).toBe(2);
  });
});

describe("try-on cost", () => {
  it("costs a flat 3 credits regardless of category", () => {
    for (const category of ["auto", "tops", "bottoms", "one-pieces"] as const) {
      expect(creditCost(tryOn({ category }))).toBe(3);
    }
  });

  it("records the provider cost estimate on the job", async () => {
    expect(estimateCostUsd(tryOn(), "mock")).toBeCloseTo(MOCK_COST_USD.tryOn);
    expect(estimateCostUsd(tryOn(), "fal")).toBeCloseTo(0.075);
    const job = await createJob(u, tryOn());
    expect(job.costUsd).toBeCloseTo(MOCK_COST_USD.tryOn);
  });
});
